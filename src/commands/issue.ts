import { execFile } from 'node:child_process';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { AI_TOOLS } from '../core/config.js';

const AI_WORKFLOW_DIR = 'ai-workflow';
const LEGACY_KEAVEAI_DIR = 'keaveai';
const CODEX_SKILLS_DIR = path.join('.codex', 'skills');
const EXCLUDED_AI_WORKFLOW_DIRS = new Set(['sdd', 'wiki', 'memory']);
const EXCLUDED_LEGACY_KEAVEAI_DIRS = new Set(['sdd', 'wiki']);
const DEFAULT_KEAVEAI_DATABASE_REPO = 'http://gitlab.metac-inc.com/front/weaveai-database.git';
const DEFAULT_TARGET_BRANCH = 'main';
const DEFAULT_DESCRIPTION = 'Syncs Codex skills and AI workflow assets generated by `keaveai init`.';

export interface IssueCommandOptions {
  remote?: string;
  target?: string;
  branch?: string;
  title?: string;
  message?: string;
  description?: string;
  include?: string;
  dryRun?: boolean;
}

export interface CommandResult {
  stdout: string;
  stderr: string;
  exitCode: number;
}

export type CommandRunner = (
  command: string,
  args: string[],
  options: { cwd: string }
) => Promise<CommandResult>;

function runCommand(command: string, args: string[], options: { cwd: string }): Promise<CommandResult> {
  return new Promise((resolve) => {
    execFile(
      command,
      args,
      {
        cwd: options.cwd,
        encoding: 'utf-8',
        maxBuffer: 1024 * 1024 * 10,
      },
      (error, stdout, stderr) => {
        const maybeCode = (error as NodeJS.ErrnoException | null)?.code;
        const exitCode = typeof maybeCode === 'number' ? maybeCode : error ? 1 : 0;
        resolve({
          stdout: typeof stdout === 'string' ? stdout : String(stdout ?? ''),
          stderr: typeof stderr === 'string' ? stderr : String(stderr ?? ''),
          exitCode,
        });
      }
    );
  });
}

function dedupe(values: string[]): string[] {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const value of values) {
    if (!seen.has(value)) {
      seen.add(value);
      result.push(value);
    }
  }
  return result;
}

function assertSafeRelativePath(value: string): string {
  const trimmed = value.trim();
  if (!trimmed) {
    throw new Error('Empty path in --include');
  }
  if (path.isAbsolute(trimmed)) {
    throw new Error(`--include path must be relative: ${trimmed}`);
  }

  const parts = trimmed.split(/[\\/]+/);
  if (parts.includes('..')) {
    throw new Error(`--include path cannot contain '..': ${trimmed}`);
  }

  return path.normalize(trimmed);
}

export function buildDefaultTitle(cwd: string = process.cwd()): string {
  return `sync ai workflow and codex skills from ${path.basename(cwd)}`;
}

export function getDefaultIssuePaths(): string[] {
  return dedupe([
    AI_WORKFLOW_DIR,
    ...AI_TOOLS
      .flatMap((tool) => tool.skillsDir ? [path.join(tool.skillsDir, 'skills')] : []),
  ]);
}

export function parseIncludePaths(include?: string): string[] {
  if (!include || include.trim().length === 0) {
    return getDefaultIssuePaths();
  }

  const tokens = include
    .split(',')
    .map((token) => token.trim())
    .filter(Boolean);

  if (tokens.length === 0) {
    throw new Error('The --include option requires at least one path.');
  }

  return dedupe(tokens.map(assertSafeRelativePath));
}

export function resolveInitializedContentPaths(cwd: string, include?: string): string[] {
  const requested = parseIncludePaths(include);
  return requested.filter((candidate) =>
    fs.existsSync(path.join(cwd, candidate))
  );
}

export function mapIssueTargetPath(relativePath: string): string {
  return path.normalize(relativePath);
}

export function getTargetIssuePaths(relativePaths: string[]): string[] {
  return dedupe(relativePaths.map(mapIssueTargetPath));
}

function isExcludedIssuePath(relativePath: string): boolean {
  const parts = path.normalize(relativePath).split(path.sep);
  if (parts.length < 2) {
    return false;
  }

  if (parts[0] === AI_WORKFLOW_DIR) {
    return EXCLUDED_AI_WORKFLOW_DIRS.has(parts[1]);
  }

  return parts[0] === LEGACY_KEAVEAI_DIR && EXCLUDED_LEGACY_KEAVEAI_DIRS.has(parts[1]);
}

export function parsePorcelainStatus(output: string): string[] {
  return output
    .split(/\r?\n/)
    .map((line) => line.trimEnd())
    .filter(Boolean)
    .map((line) => {
      const rawPath = line.slice(3).trim();
      const renameSeparator = ' -> ';
      const renameIndex = rawPath.indexOf(renameSeparator);
      return renameIndex >= 0
        ? rawPath.slice(renameIndex + renameSeparator.length)
        : rawPath;
    });
}

export async function listFilesForPaths(cwd: string, relativePaths: string[]): Promise<string[]> {
  const files: string[] = [];

  async function walk(relativePath: string): Promise<void> {
    if (isExcludedIssuePath(relativePath)) {
      return;
    }

    const fullPath = path.join(cwd, relativePath);
    const stat = await fs.promises.stat(fullPath);

    if (stat.isDirectory()) {
      const entries = await fs.promises.readdir(fullPath, { withFileTypes: true });
      for (const entry of entries) {
        await walk(path.join(relativePath, entry.name));
      }
      return;
    }

    if (stat.isFile()) {
      files.push(mapIssueTargetPath(relativePath));
    }
  }

  for (const relativePath of relativePaths) {
    await walk(relativePath);
  }

  return files.sort();
}

export function buildDefaultBranchName(now = new Date()): string {
  const stamp = now
    .toISOString()
    .replace(/\.\d{3}Z$/, 'Z')
    .replace(/[:]/g, '-');
  return `keaveai/init-${stamp}`;
}

export function buildGitLabMergeRequestPushArgs(options: {
  remote: string;
  branch: string;
  target: string;
  title: string;
  description: string;
}): string[] {
  const args = [
    'push',
    '-o',
    'merge_request.create',
    '-o',
    `merge_request.target=${options.target}`,
    '-o',
    `merge_request.title=${options.title}`,
  ];

  if (options.description.trim().length > 0) {
    args.push('-o', `merge_request.description=${options.description}`);
  }

  args.push(options.remote, options.branch);
  return args;
}

function extractFirstUrl(output: string): string | undefined {
  const match = output.match(/https?:\/\/[^\s]+/);
  return match?.[0];
}

function formatCommand(args: string[]): string {
  return `git ${args.map((arg) => {
    if (/^[A-Za-z0-9_./:=@-]+$/.test(arg)) return arg;
    return JSON.stringify(arg);
  }).join(' ')}`;
}

export class IssueCommand {
  constructor(
    private readonly runner: CommandRunner = runCommand,
    private readonly cwd: string = process.cwd()
  ) {}

  async execute(options: IssueCommandOptions = {}): Promise<void> {
    const initializedPaths = resolveInitializedContentPaths(this.cwd, options.include);
    if (initializedPaths.length === 0) {
      throw new Error(
        `No initialized KeaveAI content found. Run 'keaveai init' first, or pass --include with paths to submit.`
      );
    }

    const target = this.normalizeValue(options.target) ?? DEFAULT_TARGET_BRANCH;
    const remote = this.normalizeValue(options.remote) ?? DEFAULT_KEAVEAI_DATABASE_REPO;
    const title = this.normalizeValue(options.title) ?? buildDefaultTitle(this.cwd);
    const description = this.normalizeValue(options.description) ?? DEFAULT_DESCRIPTION;
    const commitMessage = this.normalizeValue(options.message) ?? title;
    const branch = this.normalizeValue(options.branch) ?? buildDefaultBranchName();
    const targetPaths = getTargetIssuePaths(initializedPaths);
    const pushArgs = buildGitLabMergeRequestPushArgs({
      remote,
      branch,
      target,
      title,
      description,
    });

    this.printPlan({
      branch,
      target,
      remote,
      title,
      commitMessage,
      includePaths: initializedPaths,
      targetPaths,
      files: options.dryRun ? await listFilesForPaths(this.cwd, initializedPaths) : undefined,
      pushArgs,
      dryRun: Boolean(options.dryRun),
    });

    if (options.dryRun) {
      return;
    }

    await this.ensureRemoteBranchAvailable(remote, branch);

    const tempRoot = await fs.promises.mkdtemp(path.join(os.tmpdir(), 'keaveai-issue-'));
    const repoDir = path.join(tempRoot, 'keaveai-database');

    try {
      await this.git(['clone', '--depth', '1', '--branch', target, remote, repoDir], undefined, tempRoot);
      await this.git(['checkout', '-b', branch], undefined, repoDir);

      await this.copyInitializedContent(initializedPaths, repoDir);

      const changedFiles = await this.getChangedFiles(targetPaths, repoDir);
      if (changedFiles.length === 0) {
        console.log('No initialized KeaveAI changes found to submit.');
        return;
      }

      await this.git(['add', '--', ...targetPaths], undefined, repoDir);

      const stagedCheck = await this.git(
        ['diff', '--cached', '--quiet', '--', ...targetPaths],
        [0, 1],
        repoDir
      );
      if (stagedCheck.exitCode === 0) {
        throw new Error('No staged KeaveAI changes found after git add.');
      }

      await this.git(['commit', '-m', commitMessage], undefined, repoDir);
      const pushResult = await this.git(pushArgs, undefined, repoDir);
      const mergeRequestUrl = extractFirstUrl(`${pushResult.stdout}\n${pushResult.stderr}`);

      console.log();
      console.log('KeaveAI initialized content pushed.');
      if (mergeRequestUrl) {
        console.log(`Merge request: ${mergeRequestUrl}`);
      } else {
        console.log('Merge request creation requested via GitLab push options.');
      }
    } finally {
      await fs.promises.rm(tempRoot, { recursive: true, force: true });
    }
  }

  private normalizeValue(value?: string): string | undefined {
    const normalized = value?.trim();
    return normalized && normalized.length > 0 ? normalized : undefined;
  }

  private async getChangedFiles(paths: string[], cwd: string): Promise<string[]> {
    const result = await this.git(['status', '--porcelain', '--', ...paths], undefined, cwd);
    return parsePorcelainStatus(result.stdout);
  }

  private async ensureRemoteBranchAvailable(remote: string, branch: string): Promise<void> {
    const result = await this.git(
      ['ls-remote', '--heads', remote, branch],
      [0, 1]
    );
    if (result.stdout.trim().length > 0) {
      throw new Error(`Remote branch '${branch}' already exists. Pass --branch with a new name.`);
    }
  }

  private async copyInitializedContent(pathsToCopy: string[], repoDir: string): Promise<void> {
    for (const relativePath of pathsToCopy) {
      const sourcePath = path.join(this.cwd, relativePath);
      const targetPath = path.join(repoDir, mapIssueTargetPath(relativePath));
      const stat = await fs.promises.stat(sourcePath);

      if (stat.isDirectory()) {
        await this.copyDirectory(relativePath, targetPath);
        continue;
      }

      if (isExcludedIssuePath(relativePath)) {
        continue;
      }

      await fs.promises.rm(targetPath, { recursive: true, force: true });
      await fs.promises.mkdir(path.dirname(targetPath), { recursive: true });
      await fs.promises.cp(sourcePath, targetPath, { recursive: true, force: true });
    }
  }

  private async copyDirectory(sourceRelativePath: string, targetPath: string): Promise<void> {
    if (isExcludedIssuePath(sourceRelativePath)) {
      return;
    }

    await this.prepareTargetDirectory(sourceRelativePath, targetPath);

    const sourcePath = path.join(this.cwd, sourceRelativePath);
    const entries = await fs.promises.readdir(sourcePath, { withFileTypes: true });
    for (const entry of entries) {
      const sourceChild = path.join(sourceRelativePath, entry.name);
      if (isExcludedIssuePath(sourceChild)) {
        continue;
      }

      const targetChild = path.join(targetPath, entry.name);
      await fs.promises.rm(targetChild, { recursive: true, force: true });
      await fs.promises.mkdir(path.dirname(targetChild), { recursive: true });
      await fs.promises.cp(path.join(this.cwd, sourceChild), targetChild, {
        recursive: true,
        force: true,
      });
    }
  }

  private async prepareTargetDirectory(sourceRelativePath: string, targetPath: string): Promise<void> {
    await fs.promises.mkdir(targetPath, { recursive: true });

    const normalizedSourcePath = path.normalize(sourceRelativePath);
    if (normalizedSourcePath === AI_WORKFLOW_DIR || normalizedSourcePath === LEGACY_KEAVEAI_DIR) {
      const entries = await fs.promises.readdir(targetPath, { withFileTypes: true });
      const excludedDirs = normalizedSourcePath === AI_WORKFLOW_DIR
        ? EXCLUDED_AI_WORKFLOW_DIRS
        : EXCLUDED_LEGACY_KEAVEAI_DIRS;
      for (const entry of entries) {
        if (excludedDirs.has(entry.name)) {
          continue;
        }
        await fs.promises.rm(path.join(targetPath, entry.name), { recursive: true, force: true });
      }
      return;
    }

    await fs.promises.rm(targetPath, { recursive: true, force: true });
    await fs.promises.mkdir(targetPath, { recursive: true });
  }

  private printPlan(plan: {
    branch: string;
    target: string;
    remote: string;
    title: string;
    commitMessage: string;
    includePaths: string[];
    targetPaths: string[];
    files?: string[];
    pushArgs: string[];
    dryRun: boolean;
  }): void {
    console.log(plan.dryRun ? 'KeaveAI issue dry run:' : 'KeaveAI issue plan:');
    console.log(`  Branch: ${plan.branch}`);
    console.log(`  Target: ${plan.target}`);
    console.log(`  Remote: ${plan.remote}`);
    console.log(`  Title: ${plan.title}`);
    console.log(`  Commit: ${plan.commitMessage}`);
    console.log(`  Include: ${plan.includePaths.join(', ')}`);
    console.log(`  Remote paths: ${plan.targetPaths.join(', ')}`);
    if (plan.files) {
      console.log();
      console.log('Files:');
      for (const file of plan.files) {
        console.log(`  ${file}`);
      }
    }
    console.log();
    console.log(`Push: ${formatCommand(plan.pushArgs)}`);
  }

  private async git(args: string[], okExitCodes = [0], cwd = this.cwd): Promise<CommandResult> {
    const result = await this.runner('git', args, { cwd });
    if (!okExitCodes.includes(result.exitCode)) {
      const message = result.stderr.trim() || result.stdout.trim() || `git exited with ${result.exitCode}`;
      throw new Error(`git ${args.join(' ')} failed: ${message}`);
    }
    return result;
  }
}
